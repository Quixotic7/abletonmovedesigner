/** A character's glyph index, as the core's glyph_index: -1 a space, an unknown one '?'. */
export function egGlyphIndex(ch: string): number {
  let c = ch.codePointAt(0) ?? 32
  if (c >= 97 && c <= 122) c -= 32
  if (c === 32 || c === 0xa0) return -1
  if (c === 0x2212 || c === 0x2013 || c === 0x2014) c = 45
  if (c > 32 && c < 127) return c - 32
  const x = EG_XCHAR.indexOf(c)
  return x >= 0 ? 95 + x : 63 - 32
}
